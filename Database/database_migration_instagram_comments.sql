-- Instagram por publicação/local usando apify~instagram-scraper.
-- Execute uma vez em homologação e depois em produção.

CREATE TABLE IF NOT EXISTS instagram_runs (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    tenant_id INT NOT NULL,
    user_id INT NOT NULL,
    mode ENUM('post','location') NOT NULL,
    input_value VARCHAR(500) NOT NULL,
    normalized_location VARCHAR(180) DEFAULT NULL,
    status VARCHAR(24) NOT NULL DEFAULT 'queued',
    stage VARCHAR(24) NOT NULL DEFAULT 'comments',
    requested_posts INT NOT NULL DEFAULT 0,
    requested_comments INT NOT NULL DEFAULT 0,
    max_total_comments INT NOT NULL DEFAULT 300,
    external_run_id VARCHAR(80) DEFAULT NULL,
    dataset_id VARCHAR(80) DEFAULT NULL,
    actor_id VARCHAR(100) DEFAULT 'apify~instagram-scraper',
    api_key_id INT DEFAULT NULL,
    child_runs_json LONGTEXT DEFAULT NULL,
    leads_json LONGTEXT DEFAULT NULL,
    posts_found INT NOT NULL DEFAULT 0,
    comments_collected INT NOT NULL DEFAULT 0,
    leads_found INT NOT NULL DEFAULT 0,
    duplicate_count INT NOT NULL DEFAULT 0,
    credits_charged INT NOT NULL DEFAULT 0,
    apify_items_count INT NOT NULL DEFAULT 0,
    error_category VARCHAR(64) DEFAULT NULL,
    error_message TEXT DEFAULT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    started_at DATETIME DEFAULT NULL,
    finished_at DATETIME DEFAULT NULL,
    PRIMARY KEY (id),
    KEY idx_instagram_runs_tenant_status (tenant_id, status),
    KEY idx_instagram_runs_external (external_run_id),
    KEY idx_instagram_runs_created (created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS instagram_leads (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    tenant_id INT NOT NULL,
    run_id BIGINT UNSIGNED NOT NULL,
    profile_key VARCHAR(255) NOT NULL,
    owner_id VARCHAR(120) DEFAULT NULL,
    username VARCHAR(255) DEFAULT NULL,
    full_name VARCHAR(255) DEFAULT NULL,
    profile_url VARCHAR(500) DEFAULT NULL,
    comment_text TEXT DEFAULT NULL,
    commented_at VARCHAR(64) DEFAULT NULL,
    source_post_url VARCHAR(500) NOT NULL,
    interest_level VARCHAR(16) NOT NULL DEFAULT 'low',
    comments_count INT NOT NULL DEFAULT 1,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uq_instagram_lead_tenant_profile (tenant_id, profile_key),
    KEY idx_instagram_leads_run (run_id),
    KEY idx_instagram_leads_interest (tenant_id, interest_level),
    CONSTRAINT fk_instagram_leads_run FOREIGN KEY (run_id) REFERENCES instagram_runs(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
