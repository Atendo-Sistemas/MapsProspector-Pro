CREATE TABLE `asaas_subscriptions` (
  `id` bigint unsigned NOT NULL AUTO_INCREMENT,
  `tenant_id` int unsigned NOT NULL,
  `user_id` int unsigned NOT NULL,
  `plan_id` int unsigned NOT NULL,
  `plan_slug` varchar(64) COLLATE utf8mb4_unicode_ci NOT NULL,
  `product_kind` varchar(32) COLLATE utf8mb4_unicode_ci NOT NULL DEFAULT 'prospecting' COMMENT 'prospecting | crm_addon',
  `amount_cents` int unsigned NOT NULL,
  `asaas_customer_id` varchar(64) COLLATE utf8mb4_unicode_ci DEFAULT NULL,
  `asaas_subscription_id` varchar(128) COLLATE utf8mb4_unicode_ci NOT NULL,
  `payment_url` varchar(500) COLLATE utf8mb4_unicode_ci DEFAULT NULL,
  `status` enum('pending','active','cancelled','overdue','expired') COLLATE utf8mb4_unicode_ci NOT NULL DEFAULT 'pending',
  `next_due_date` date DEFAULT NULL,
  `access_until` date DEFAULT NULL,
  `cancelled_at` datetime DEFAULT NULL,
  `last_payment_id` varchar(64) COLLATE utf8mb4_unicode_ci DEFAULT NULL,
  `last_payment_status` varchar(32) COLLATE utf8mb4_unicode_ci DEFAULT NULL,
  `created_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_asaas_subscription_id` (`asaas_subscription_id`),
  KEY `idx_subscription_tenant_status` (`tenant_id`,`status`),
  KEY `idx_subscription_access_until` (`access_until`),
  KEY `idx_subscription_next_due_date` (`next_due_date`),
  KEY `idx_subscription_last_payment` (`last_payment_id`)
) ENGINE=InnoDB AUTO_INCREMENT=3 DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
